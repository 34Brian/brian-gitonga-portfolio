
import Project from "../models/Project.js";

export const getProjects = async (req, res, next) => {
  try {
    const projects = await Project.find({ published: true }).sort({
      order: 1,
      createdAt: -1,
    });

    res.status(200).json({
      success: true,
      count: projects.length,
      data: projects,
    });
  } catch (error) {
    next(error);
  }
};

